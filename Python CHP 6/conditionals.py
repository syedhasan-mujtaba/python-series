#DEFINITION OF CONDITIONALS: 
""" Conditionals are used to perform different actions based on different conditions.
In Python, we use if, elif, and else statements to implement conditionals. """

#SYNTAX OF IF-ELSE STATEMENT:
if condition:
    # code to execute if condition is True
    pass
else:
    # code to execute if condition is False
    pass

#NOTE:There is indentation in Python that is used to define blocks of code. The code inside the if, elif, and else statements must be indented consistently. Indentation is typically done using four spaces or a tab.

#IF-ELSE STATEMENT EXAMPLE:
x = 10
if x > 5:
    print("x is greater than 5")
else:
    print("x is not greater than 5")
#OUTPUT: x is greater than 5

#WARNING: Be careful with the indentation. If the indentation is not consistent, it will result in an IndentationError.