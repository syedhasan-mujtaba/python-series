#WHAT IS ITERATION?
""" Iteration is the process of repeating a set of instructions or actions until a certain condition is met.
In programming, iteration is often used to process collections of data, such as lists or arrays. """

#SYNTAX:
""" list_name = [item1, item2, item3, ...]
index = 0
while index < len(list_name):
    print(list_name[index])
    index += 1 """

#EXAMPLE:
l=[1, 2, 3, 4, 5]
