#FOR LOOP IN PYTHON:
""" A for loop is used to iterate over a sequence (such as a list, tuple, or string) and execute a block of code for each item in the sequence. """
#SYNTAX:
""" for item in sequence:
    # block of code to be executed """


 #RANGE FUNCTION:
""" The range() function is used to generate a sequence of numbers.
It can be used in a for loop to iterate over a specific range of numbers. """
#SYNTAX:
""" range(start, stop, step_size) """

#NOTE: Step size is optional feature which is used to specify the increment between each number in the sequence. If not specified, the default step size is 1.