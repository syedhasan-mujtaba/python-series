#LOOPS IN PYTHON:
""" Loops are used to execute a block of code repeatedly until a certain condition is met. """

#TYPES OF LOOPS:

#1. FOR LOOP:
""" A for loop is used to iterate over a sequence (such as a list, tuple, dictionary, set, or string) and execute a block of code for each item in the sequence. """
#2. WHILE LOOP:
""" A while loop is used to execute a block of code repeatedly as long as a certain condition is true. """

#NOTE:
""" Python also has a special type of loop called a "nested loop," which is a loop inside another loop. 
Nested loops can be used to iterate over multi-dimensional data structures, such as lists of lists or matrices. """