#ITERATION IN FOR LOOP:
""" Iteration is the process of executing a block of code repeatedly for each item in a sequence. 
In a for loop, iteration is achieved by using the loop variable to access each item in the sequence one by one. """

#FOR LOOP WITH LISTS:
l = [1, 2, 3, 4, 5]
for item in l:
    print(item)

#FOR LOOP WITH TUPLES:
t = (1, 2, 3, 4, 5)
for item in t:
    print(item)

#FOR LOOP WITH STRINGS:
s = "Hello"
for item in s:
    print(item)