# 12. CASE SENSITIVITY
# ------------------------------------------------------------

# Python is case-sensitive.
#
# name, Name, and NAME can represent different identifiers.

name = "Hassan"
Name = "Python"

print(name)
print(Name)


# ------------------------------------------------------------
# 13. IDENTIFIERS
# ------------------------------------------------------------

# An identifier is a name used for variables, functions,
# classes, and other objects.
#
# General rules:
# - Can contain letters, digits, and underscores
# - Cannot start with a digit
# - Cannot contain spaces
# - Cannot be a Python keyword
# - Is case-sensitive
#
# Valid examples:
# name
# student_name
# age2
# _value
#
# Invalid examples:
# 2name
# student name
# class


# ------------------------------------------------------------
# 14. PYTHON KEYWORDS
# ------------------------------------------------------------

