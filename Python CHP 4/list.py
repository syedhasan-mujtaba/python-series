#DEFINITION:
"""
PYTHON LISTS ARE CONTAINERS TO STORE A SET OF VALUES OF ANY DATA TYPES.
SYNTAX: list_name=[value1, value2, value3, ...]
"""
#NOTE: PYTHON LISTS ARE MUTABLE, MEANING THAT WE CAN CHANGE THE VALUES OF THE ELEMENTS IN A LIST UNLIKE STRINGS, WHICH ARE IMMUTABLE.

#EXAMPLES:
friends=["John", "Mike", 56, 6.5, False, "Emma"]
print(friends[0]) #OUTPUT: John
friends[0]="David" #CHANGING THE VALUE OF THE FIRST ELEMENT
print(friends) #OUTPUT: ['David', 'Mike', 56, 6.5, False, 'Emma']

#LIST INDEXING:
"""
LIST INDEXING IS USED TO ACCESS THE ELEMENTS OF A LIST USING THEIR POSITIONAL INDEX.
THE INDEX OF THE FIRST ELEMENT IS 0, THE INDEX OF THE SECOND ELEMENT IS 1, AND SO ON (JUST LIKE STRINGS).
SYNTAX: list_name[index]
"""
#LIST SLICING:
"""
LIST SLICING IS USED TO ACCESS A SUBSET OF ELEMENTS FROM A LIST USING A RANGE OF INDEXES (SAME AS STRINGS).
SYNTAX: list_name[start_index:end_index]
EXAMPLE: friends[1:4] #OUTPUT: ['Mike', 56, 6.5]
"""
