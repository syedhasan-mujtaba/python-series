#IMPORTANT NOTE:
"""TUPLES ARE IMMUTABLE, MEANING THEIR CONTENTS CANNOT BE CHANGED AFTER CREATION.
 ONCE A TUPLE IS CREATED, ITS ELEMENTS CANNOT BE MODIFIED, ADDED, OR REMOVED.
 (JUST LIKE STRINGS, WHICH ARE IMMUTABLE). 
"""

#DIFFERENCE BETWEEN STRINGS, LISTS, AND TUPLES:
"""
- STRINGS: IMMUTABLE SEQUENCES OF CHARACTERS.
- LISTS: MUTABLE SEQUENCES OF ELEMENTS.
- TUPLES: IMMUTABLE SEQUENCES OF ELEMENTS.
"""

#USE OF TUPLES:
"""
TUPLES ARE USED TO STORE A COLLECTION OF ELEMENTS, SIMILAR TO LISTS, BUT THEY ARE IMMUTABLE.
"""

#SYNTAX DIFFERENCE BETWEEN LISTS AND TUPLES:
"""
- LISTS ARE DEFINED WITH SQUARE BRACKETS: [element1, element2, ...]
- TUPLES ARE DEFINED WITH PARENTHESES: (element1, element2, ...)
"""

#NOTE: IF A TUPLE CONTAINS ONLY ONE ELEMENT, A COMMA MUST BE PLACED AFTER THE ELEMENT TO DISTINGUISH IT FROM A REGULAR PARENTHESIS.
#NOTE: TUPLES CAN CONTAIN ELEMENTS OF DIFFERENT DATA TYPES, JUST LIKE LISTS.

#EXAMPLE:
a=(1, 23, 567, False, "Hello")
print(a[3]) #OUTPUT: False
print(type(a)) #OUTPUT: <class 'tuple'>  

#TUPLE SLICING:
print(a[1:4]) #OUTPUT: (23, 567, False)
print(a[:4]) #OUTPUT: (1, 23, 567, False)
print(a[2:]) #OUTPUT: (567, False, 'Hello')
print(a[:]) #OUTPUT: (1, 23, 567, False, 'Hello')
#NEGATIVE SLICING:
print(a[-1]) #OUTPUT: Hello
print(a[-3:-1]) #OUTPUT: (567, False)
print(a[-4:]) #OUTPUT: (23, 567, False, 'Hello')
print(a[:-2]) #OUTPUT: (1, 23, 567)
#SKIP SLICING:
print(a[::2]) #OUTPUT: (1, 567, 'Hello')
print(a[1::2]) #OUTPUT: (23, False)
print(a[::-1]) #OUTPUT: ('Hello', False, 567, 23, 1)
print(a[::-2]) #OUTPUT: ('Hello', 567, 1)