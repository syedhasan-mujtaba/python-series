#DEFINITION OF ESCAPE SEQUENCES IN PYTHON:
#ESCAPE SEQUENCES ARE SPECIAL CHARACTERS USED TO REPRESENT CERTAIN WHITE SPACE CHARACTERS OR OTHER CHARACTERS THAT CANNOT BE DIRECTLY TYPED IN A STRING.
#THEY ARE WRITTEN WITH A BACKSLASH (\) FOLLOWED BY THE CHARACTER YOU WANT TO REPRESENT.

#SOME COMMON ESCAPE SEQUENCES ARE:
#1. \n: REPRESENTS A NEW LINE.
#2. \t: REPRESENTS A TAB.
#3. \": REPRESENTS A DOUBLE QUOTE.
#4. \': REPRESENTS A SINGLE QUOTE.
#5. \\: REPRESENTS A BACKSLASH.