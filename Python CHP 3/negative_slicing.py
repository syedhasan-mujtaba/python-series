#STRING SLICING:
"""
STRING SLICING IS USED TO EXTRACT A PORTION OF A STRING.
THE SYNTAX FOR STRING SLICING IS: string[start:stop:step]
"""
#FOR EXAMPLE:
name="hasan"
nameshort=name[0:3] #EXTRACTS THE FIRST THREE CHARACTERS OF THE STRING
print(nameshort)

#NEGATIVE INDICES IN STRINGS:
"""
NEGATIVE INDICES STARTS FROM -1 (MINUS ONE) AND GOES UP TO -N,
 WHERE N IS THE LENGTH OF THE STRING.
""" 
#NOTE: 
"""
TO SOLVE NEGATIVE INDICES,FIRST CONVERT THE NEGATIVE
INDEX TO CORRESPONDING POSITIVE INDICES BY ADDING THE 
LENGTH OF THE STRING TO IT.
"""

#SLICING WITH SKIP VALUE:
"""
SLICING WITH A SKIP VALUE IS DONE BY SPECIFYING A THIRD PARAMETER IN THE SLICING NOTATION.
THE SYNTAX IS: string[start:stop:step]
"""
#FOR EXAMPLE:
"""
word="amazing"
word[1:6:2] #mzn
"""

#NOTE:
""" IF START INDEX IS OMITTED,
 IT IS CONSIDERED AS 0 (ZERO)."""
""" IF STOP INDEX IS OMITTED,
 IT IS CONSIDERED AS THE LENGTH OF THE STRING."""