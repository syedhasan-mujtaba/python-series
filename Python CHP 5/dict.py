#DICTIONARY IN PYTHON:
"""A dictionary is a built-in Python data structure used to store data in key-value pairs.
Each key is unique and is used to access its corresponding value."""
#NOTE: A mutable, unordered collection of unique keys and their associated values.
#NOTE: Dictionaries uses curly braces {} to define the dictionary and colons (:) to separate keys and values.

#SYNTAX: 
"""
dictionary_name = {
    key1: value1,
    key2: value2,
    key3: value3
}
"""

#EXAMPLE:
"""
student = {
    "name": "Hasan",
    "age": 17,
    "grade": "A++"
}
"""


#EMPTY DICTIONARY:
#SYNTAX: dictionary_name = {}


#KEY FEATURES:
#1. Stores data in key-value pairs.
#2. Mutable (can be modified after creation).
#3. Unordered collection.
#4. Keys must be unique.
#5. Values can be duplicated.
#6. Can store different data types.
#7. Written inside curly braces {}.
#8. Items are separated by commas.
#9. Each key and value are separated by a colon (:).

#IMPORTANT PROPERTIES:
#1. It is unordered, meaning the items do not have a defined order.
#2. It is mutable, meaning you can change its content without changing its identity.
#3. It is indexed by keys, which can be of any immutable type (like strings, numbers, or tuples).
#4. Cannot contain duplicate keys; if a key is repeated, the last value will overwrite the previous one.
