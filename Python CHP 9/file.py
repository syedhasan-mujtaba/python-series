# TYPES OF STORAGE:

# 1. Volatile Storage: This type of storage loses its data when the power is turned off. Examples include RAM (Random Access Memory) and cache memory.
# 2. Non-Volatile Storage: This type of storage retains its data even when the power is turned off. Examples include hard drives, SSDs (Solid State Drives), and flash memory.

