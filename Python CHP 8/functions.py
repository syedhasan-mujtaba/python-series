#EXAMPLE:

#FUNCTION DEFINITION:
def avg():
    a=int(input("Enter first number: "))
    b=int(input("Enter second number: "))
    """
    This function takes two numbers as input and returns their average.
    """

    avg = (a + b) / 2
    print ("Average:", avg)

#FUNCTION CALL:
avg()
avg()
